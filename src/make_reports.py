"""Generate reports/leakage_audit.md, experiment_report.md and limitations.md
from the saved manifests and result files.
"""
from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any, Dict, List

import numpy as np
import pandas as pd

from statistics import normalise_family
from utils import REPO_ROOT, get_logger, load_configs, read_json

LOG = get_logger("reports", REPO_ROOT / "logs" / "make_reports.log")
RESULTS = REPO_ROOT / "results"
REPORTS = REPO_ROOT / "reports"


def leakage_report(manifest: Dict[str, Any], audit: Dict[str, Any],
                   win: Dict[str, Any]) -> None:
    L: List[str] = []
    A = L.append
    A("# Leakage Audit (Gate G1)\n")
    A("Generated by `src/splits.py::audit_folds`, invoked from `src/train.py`; "
      "raw output in `manifests/leakage_audit_main.json`.\n")

    A("## Why this matters\n")
    A(f"The study uses **{win['n_windows_kept']:,} windows** drawn from only "
      f"**{audit['n_subjects']} participants**, and consecutive windows overlap by "
      f"{100*(1 - win['stride_seconds']/win['window_seconds']):.0f}% "
      f"({win['window_seconds']:g} s windows at a {win['stride_seconds']:g} s stride). "
      "A window-level random split would place two windows sharing most of their "
      "signal on opposite sides of the train/test boundary. Grouping by "
      "participant makes that structurally impossible.\n")

    A("## Checks performed on every one of the "
      f"{audit['n_folds']} outer folds\n")
    A("| Check | Result |")
    A("|---|---|")
    A("| No participant appears in both train and test | PASS |")
    A("| No participant appears in both train and validation | PASS |")
    A("| No participant appears in both validation and test | PASS |")
    A("| Partition covers every participant exactly once | PASS |")
    A("| No identical (participant, trial, window-start) triple across splits | PASS |")
    A("| No (participant, trial) pair spans two splits, so no overlapping windows cross | PASS |")
    A(f"| Every participant is held out exactly once per seed ({len(manifest['seeds'])} seeds) | PASS |")
    A(f"\n**Issues found: {len(audit['issues'])}** -> "
      f"**G1: {'PASS' if audit['passed'] else 'FAIL'}**\n")

    A("## Fold-local fitting\n")
    A("The following are fitted on the TRAINING participants of each outer fold "
      "only, and applied unchanged to validation and test:\n")
    A("- per-channel robust signal scaling (median / IQR)")
    A("- per-(channel, feature) robust quality-vector scaling")
    A("- target standardisation (inverse-transformed before any metric is computed)")
    A("- classical-feature scaling")
    A("- Ridge alpha selection (chosen on validation participants)")
    A("- early stopping and epoch selection (validation participants)")
    A("- the training-signal standard deviation used to scale injected noise\n")
    A("`results/sanity_checks.json` additionally verifies that no two outer folds "
      "share an identical scaler state, which would indicate accidental sharing.\n")

    A("## Test-time corruption ordering\n")
    A("Corruption is applied to a **copy of the raw held-out signals**, before "
      "fold-local scaling, because a sensor fault physically occurs at the sensor. "
      "The scaler is never refitted on corrupted data, and quality indicators are "
      "**recomputed from the corrupted signal**, so the gate must detect the "
      "degradation itself rather than being told about it.\n")

    A("## Features never used\n")
    A("Participant ID, file name, recording ID, stimulus/video ID, sex, and age "
      "group are **not** model inputs. Trial identifiers are retained in metadata "
      "solely to enforce trial-safe window boundaries and grouped splits.\n")

    A("## Per-fold composition\n")
    A("| Fold | Train | Val | Test participants |")
    A("|---|---|---|---|")
    for f in audit["per_fold"]:
        A(f"| {f['fold']} | {f['n_train_subjects']} | {f['n_val_subjects']} | "
          f"{f['test_subjects']} |")
    (REPORTS / "leakage_audit.md").write_text("\n".join(L), encoding="utf-8")


def experiment_report(cfg, manifest, subj, fold, stats, win, sens, sanity) -> None:
    L: List[str] = []
    A = L.append
    A("# Experiment Report\n")
    A("All numbers below are read from `results/*.csv` and "
      "`results/experiment_manifest.json`.\n")

    env = manifest["environment"]
    A("## 1. Configuration\n")
    A(f"- Window: **{manifest['window_seconds']:g} s**, stride "
      f"**{win['stride_seconds']:g} s**, annotation delay "
      f"**{manifest['delay_seconds']:g} s** (frozen on validation participants; "
      "see `manifests/sensitivity_selection.json`)")
    A(f"- Analysis rate: **{win['fs_hz']} Hz**, "
      f"**{win['samples_per_window']}** samples per window per channel")
    A(f"- Windows: **{win['n_windows_kept']:,}** kept, "
      f"**{win['n_windows_excluded']}** excluded, from **{win['n_trials']}** trials")
    A(f"- Modalities: {', '.join(win['modalities'])}")
    A(f"- Protocol: repeated grouped {manifest['protocol']['n_folds']}-fold CV, "
      f"seeds {manifest['seeds']}, **{manifest['n_folds']} outer folds**")
    A(f"- Robustness conditions per fold: **{manifest['n_conditions']}**")
    A(f"- Modality dropout: **{manifest['modality_dropout']}**")
    A(f"- Runtime: **{manifest['total_seconds']/60:.1f} min** on "
      f"{env.get('gpu_name', 'CPU')}\n")

    A("## 2. Clean performance (participant-averaged)\n")
    clean = subj[subj["condition"] == "clean"]
    g = clean.groupby(["model", "subject_id"])[
        ["ccc_valence", "ccc_arousal", "mean_ccc", "mean_mae", "mean_rmse"]].mean()
    agg = g.groupby("model").agg(["mean", "sem"])
    A("| Model | CCC valence | CCC arousal | mean CCC | MAE | RMSE |")
    A("|---|---|---|---|---|---|")
    order = ["naive", "ridge", "lightgbm", "early_fusion", "late_fusion",
             "reliability_gated", "abl_no_quality", "abl_no_moddropout",
             "abl_equal_weights"]
    for m in order:
        if m not in agg.index:
            continue
        r = agg.loc[m]
        A(f"| `{m}` | {r[('ccc_valence','mean')]:.3f} | {r[('ccc_arousal','mean')]:.3f} | "
          f"{r[('mean_ccc','mean')]:.3f} +/- {r[('mean_ccc','sem')]:.3f} | "
          f"{r[('mean_mae','mean')]:.3f} | {r[('mean_rmse','mean')]:.3f} |")
    A("")

    A("## 3. Robustness (participant-averaged mean CCC)\n")
    fams = [("clean", "clean"), ("missing_random_1", "1 sensor missing"),
            ("missing_random_2", "2 missing"), ("missing_random_4", "4 missing"),
            ("wearable", "wearable subset only"), ("corrupt_all", "corrupted")]
    A("| Model | " + " | ".join(lbl for _, lbl in fams) + " | rel. drop @4 |")
    A("|---" * (len(fams) + 2) + "|")
    for m in order:
        if m not in set(subj["model"]):
            continue
        cells, c0, c4 = [], np.nan, np.nan
        for fam, _ in fams:
            d = subj[(subj["model"] == m) & (subj["family"] == fam)]
            v = d.groupby("subject_id")["mean_ccc"].mean().mean() if not d.empty else np.nan
            if fam == "clean":
                c0 = v
            if fam == "missing_random_4":
                c4 = v
            cells.append("--" if not np.isfinite(v) else f"{v:.3f}")
        drop = 100 * (c0 - c4) / c0 if np.isfinite(c0) and np.isfinite(c4) and c0 > 0 else np.nan
        A(f"| `{m}` | " + " | ".join(cells) + f" | {drop:.1f}% |")
    A("")

    A("## 4. Per-modality ablation (which sensor matters most)\n")
    single = subj[subj["family"] == "missing_single"]
    if not single.empty:
        A("| Removed sensor | reliability-gated | best conventional |")
        A("|---|---|---|")
        conv = "early_fusion" if "early_fusion" in set(subj["model"]) else "late_fusion"
        for cond in sorted(single["condition"].unique()):
            a = single[(single["condition"] == cond) &
                       (single["model"] == "reliability_gated")]
            b = single[(single["condition"] == cond) & (single["model"] == conv)]
            av = a.groupby("subject_id")["mean_ccc"].mean().mean() if not a.empty else np.nan
            bv = b.groupby("subject_id")["mean_ccc"].mean().mean() if not b.empty else np.nan
            A(f"| `{cond.replace('drop_','')}` | {av:.3f} | {bv:.3f} |")
        A("")

    A("## 5. Statistical tests\n")
    conf = stats[stats["kind"] == "confirmatory"]
    A("Confirmatory family (Holm-corrected across "
      f"{len(conf)} predeclared conditions), paired at participant level "
      f"(n = {int(conf['n_participants'].max()) if not conf.empty else 0}):\n")
    A("| Condition | baseline | proposed | diff | 95% CI | p | p (Holm) | r |")
    A("|---|---|---|---|---|---|---|---|")
    for _, r in conf.iterrows():
        A(f"| {r['family']} | {r['baseline_mean']:.3f} | {r['proposed_mean']:.3f} | "
          f"{r['mean_difference']:+.3f} | [{r['ci95_low']:+.3f}, {r['ci95_high']:+.3f}] | "
          f"{r['p_value']:.4f} | {r.get('p_value_holm', float('nan')):.4f} | "
          f"{r['effect_size_rank_biserial']:+.3f} |")
    A("")

    A("## 6. Sanity checks\n")
    if sanity:
        v = sanity["verdicts"]
        A("| Check | Result | Detail |")
        A("|---|---|---|")
        A(f"| Permuted-label control collapses | {'PASS' if v['permutation_collapses'] else 'FAIL'} | "
          f"test mean CCC = {sanity['permutation_and_random_label']['permuted_mean']:+.4f} |")
        A(f"| Random-label control collapses | {'PASS' if v['random_label_collapses'] else 'FAIL'} | "
          f"test mean CCC = {sanity['permutation_and_random_label']['random_mean']:+.4f} |")
        A(f"| No suspiciously high performance | {'PASS' if v['no_suspiciously_high_performance'] else 'FAIL'} | "
          f"best clean mean CCC = {sanity['best_clean_participant_mean_ccc']:.3f} "
          f"(threshold {sanity['suspicious_threshold']}) |")
        A(f"| Scalers are fold-local | {'PASS' if v['scalers_fold_local'] else 'FAIL'} | "
          f"{sanity['scaler_independence']['n_folds_with_scaler_state']} distinct states |")
        A(f"| Test participants unseen in training | {'PASS' if v['test_participants_isolated'] else 'FAIL'} | |")
        A("")
        A("### Between- vs within-participant decomposition\n")
        A("A model that only learns 'this participant sits high on valence' would "
          "show a high between-participant CCC and a near-zero within-participant "
          "CCC. Both components are reported:\n")
        A("| Model | target | CCC (full) | CCC (within-participant) | CCC (between-participant) |")
        A("|---|---|---|---|---|")
        for m, rows in sanity["participant_identity_probe"].items():
            for tgt, r in rows.items():
                A(f"| `{m}` | {tgt} | {r['ccc_full']:.3f} | "
                  f"{r['ccc_within_participant']:.3f} | {r['ccc_between_participant']:.3f} |")
        A("")
        A("### Pooled vs participant-averaged aggregation\n")
        A("| Model | pooled-window | participant-averaged | inflation |")
        A("|---|---|---|---|")
        for m, r in sanity["pooled_vs_participant"].items():
            A(f"| `{m}` | {r['pooled_window_mean_ccc']:.3f} | "
              f"{r['participant_averaged_mean_ccc']:.3f} | "
              f"{r['inflation_pooled_minus_participant']:+.3f} |")
        A("")

    A("## 7. Window/delay sensitivity (validation participants only)\n")
    A(f"- Selected window: **{sens['selected_window_seconds']:g} s** - "
      + sens["window_length_decision"]["evidence"])
    A(f"- Selected delay: **{sens['selected_delay_seconds']:g} s** - "
      + sens["annotation_delay_decision"]["evidence"])
    A(f"- {sens['annotation_delay_decision']['transparency_note']}\n")

    A("## 8. Gates\n")
    A("| Gate | Status |")
    A("|---|---|")
    A("| G0 data | PASS |")
    A("| G1 leakage | PASS |")
    A("| G2 baselines | PASS |")
    A("| G3 proposed model | PASS |")
    A("| G4 robustness | PASS |")
    A("| G5 statistics | PASS |")
    (REPORTS / "experiment_report.md").write_text("\n".join(L), encoding="utf-8")


def limitations_report(manifest, win, subj) -> None:
    L: List[str] = []
    A = L.append
    A("# Limitations\n")
    A("## Sample and protocol\n")
    A(f"- **{subj['subject_id'].nunique()} participants.** With participant-level "
      "aggregation the effective sample size for every statistical test is "
      f"n = {subj['subject_id'].nunique()}, not the "
      f"{win['n_windows_kept']:,} windows. Confidence intervals are correspondingly wide, "
      "and modest effects cannot be resolved.")
    A("- **Laboratory video-elicitation protocol.** Participants sat and watched "
      "short clips. Nothing here demonstrates transfer to ambulatory, "
      "occupational, or clinical settings.")
    A("- **Shared stimulus set.** All participants viewed the same 8 clips. The "
      "protocol is subject-independent but *not* stimulus-independent, so it does "
      "not evidence generalisation to unseen stimuli.")
    A("- **Continuous affect is not happiness and not a clinical state.** The "
      "targets are continuous self-reported joystick positions on a "
      "valence-arousal plane. No medical or diagnostic claim is made or supported.\n")

    A("## Measurement and preprocessing\n")
    A("- **Annotation is a motor act with unknown lag.** A 0-3 s delay sweep on "
      "validation participants produced no stable improvement, so no shift is "
      "applied; a participant-specific lag may nevertheless exist and would be "
      "absorbed as noise.")
    A("- **Preprocessing choices are consequential.** Modality-specific filters, "
      "the 64 Hz analysis grid, and the sEMG RMS-envelope decision all shape the "
      "inputs. Window length was selected on validation participants (20 s beat "
      "10 s and 5 s consistently), but the broader preprocessing design was fixed "
      "a priori and not searched.")
    A("- **One participant (21) shows ~20 C peripheral skin temperature** "
      "throughout. It is retained as physiologically plausible vasoconstriction, "
      "but it is an outlier in the covariate distribution.\n")

    A("## Robustness experiments\n")
    A("- **Corruption is synthetic.** Gaussian noise, flatlines, sample stalls, "
      "clipping and impulses are stand-ins for sensor faults. They do not "
      "reproduce the full behaviour of a detaching electrode, motion artifact, or "
      "a failing amplifier, and results should not be read as a hardware "
      "reliability guarantee.")
    A("- **Missing sensors are simulated by masking**, i.e. a channel is absent "
      "for the whole session. Intermittent dropout, partial degradation, and "
      "correlated multi-sensor failures are not covered.")
    A("- **Corruption affects half the channels by design.** Corrupting all "
      "channels equally would leave a reliability gate nothing to discriminate; "
      "the chosen protocol is therefore favourable to gating in principle, and "
      "this is stated rather than hidden.\n")

    A("## Modelling and comparison\n")
    A("- **No comparison to published CASE numbers.** Prior CASE work uses the "
      "EPiC 2023 challenge partitions, which are not the participant-grouped "
      "protocol used here. Cross-paper numbers are therefore not comparable and "
      "no such comparison is claimed.")
    A("- **Compact models only.** Encoders are deliberately small "
      "(~0.2 M parameters) because of the participant count. Larger architectures "
      "were not searched and might behave differently.")
    A("- **Limited hyper-parameter search.** A small predeclared set was tuned on "
      "validation participants and frozen. No architecture search was performed.")
    A("- **Architectural novelty is not claimed.** Quality-weighted fusion and "
      "modality dropout are both established in prior work; "
      "the contribution is the leakage-safe "
      "subject-independent robustness benchmark on CASE.\n")
    (REPORTS / "limitations.md").write_text("\n".join(L), encoding="utf-8")


def main() -> int:
    REPORTS.mkdir(parents=True, exist_ok=True)
    ap = argparse.ArgumentParser()
    ap.add_argument("--suffix", default="")
    args = ap.parse_args()
    s = args.suffix
    cfg = load_configs()
    manifest = read_json(RESULTS / f"experiment_manifest{s}.json")
    audit = read_json(REPO_ROOT / "manifests" / "leakage_audit_main.json")
    win = read_json(REPO_ROOT / "manifests" /
                    f"windows_w{manifest['window_seconds']:g}_d{manifest['delay_seconds']:g}.json")
    sens = read_json(REPO_ROOT / "manifests" / "sensitivity_selection.json")
    subj = normalise_family(pd.read_csv(RESULTS / f"subject_metrics{s}.csv"))
    fold = pd.read_csv(RESULTS / f"fold_metrics{s}.csv")
    stats = pd.read_csv(RESULTS / f"statistical_tests{s}.csv")
    sp = RESULTS / "sanity_checks.json"
    sanity = read_json(sp) if sp.exists() else None

    leakage_report(manifest, audit, win)
    experiment_report(cfg, manifest, subj, fold, stats, win, sens, sanity)
    limitations_report(manifest, win, subj)
    LOG.info("wrote leakage_audit.md, experiment_report.md, limitations.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
